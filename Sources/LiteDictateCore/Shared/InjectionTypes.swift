import Foundation

public enum ClipboardReadiness: Equatable, Sendable {
    case idle
    case busy
}

public enum InjectionBlockReason: String, Equatable, Sendable {
    case concealedContent
    case filePromise
    case largeImageOrUnsupported
    case snapshotExceededBudget
    case terminalUnsafeCharacters
    case pasteboardAccessDenied
    case changeCountMismatch
    case eventPostFailed

    public var userMessage: String {
        switch self {
        case .concealedContent:
            return "剪贴板里有私密内容，已为你把文字保存在这里，不会覆盖原剪贴板"
        case .filePromise:
            return "剪贴板里有待复制的文件，已为你把文字保存在这里，不会覆盖原剪贴板"
        case .largeImageOrUnsupported:
            return "剪贴板里有图片或特殊内容，已为你把文字保存在这里，不会覆盖原剪贴板"
        case .snapshotExceededBudget:
            return "剪贴板内容较大，已为你把文字保存在这里，避免影响原剪贴板"
        case .terminalUnsafeCharacters:
            return "目标窗口是终端且文字包含换行，为防止误执行命令，请确认后再插入"
        case .pasteboardAccessDenied:
            return "系统限制了剪贴板访问，可以直接点击下方按钮复制或插入"
        case .changeCountMismatch:
            return "刚刚复制了新内容，已为你把文字保留在这里"
        case .eventPostFailed:
            return "文字输入未成功，请检查系统「自动输入文字」权限"
        }
    }
}

public enum DirectInsertMethod: String, Equatable, Sendable {
    case verifiedAccessibility
    case unicodeKeystrokeStream
}

public enum DirectInjectionOutcome: Equatable, Sendable {
    case inserted(method: DirectInsertMethod)
    case partiallyInserted(remainingText: String, reason: String)
    case blocked(InjectionBlockReason)
}

/// Direct natural text insertion contract with ZERO `NSPasteboard` touch.
public protocol DirectTextInjecting: AnyObject, Sendable {
    func isTerminalApplication(bundleIdentifier: String?) -> Bool

    /// Returns `false` if text contains `\n`, `\r`, or any control char `< 0x20` (except `\t`) or `0x7F` / line separators.
    func isTextSafeForTerminal(_ text: String) -> Bool

    /// Inserts `text` directly without touching the clipboard, verifying `focusGeneration` continuously.
    func insertTextDirectly(
        _ text: String,
        targetPID: pid_t,
        targetBundleIdentifier: String?,
        expectedFocusGeneration: UInt64,
        currentFocusGeneration: @escaping @Sendable () -> UInt64,
        completion: @escaping @Sendable (DirectInjectionOutcome) -> Void
    )
}

public struct InjectionPreparation: Equatable, Sendable {
    public let transactionID: UInt64
    public let expectedChangeCount: Int
    public let hadSnapshot: Bool

    public init(transactionID: UInt64, expectedChangeCount: Int, hadSnapshot: Bool) {
        self.transactionID = transactionID
        self.expectedChangeCount = expectedChangeCount
        self.hadSnapshot = hadSnapshot
    }
}

public enum InjectionPreparationResult: Equatable, Sendable {
    case ready(InjectionPreparation)
    case blocked(InjectionBlockReason)
}

public protocol ClipboardInjecting: AnyObject, Sendable {
    var readiness: ClipboardReadiness { get }

    /// Invokes `callback` asynchronously once clipboard state machine is `.idle`.
    /// NEVER cancels an in-flight restore timer.
    func whenIdle(_ callback: @escaping @Sendable () -> Void)

    func isTerminalApplication(bundleIdentifier: String?) -> Bool

    /// Returns `false` if text contains `\n`, `\r`, or any control char `< 0x20` (except `\t`) or `0x7F`.
    func isTextSafeForTerminal(_ text: String) -> Bool

    /// Tiered prescreening + 8 MiB bounded snapshot + write text with TransientType & AutoGeneratedType.
    func preparePaste(
        text: String,
        targetBundleIdentifier: String?,
        completion: @escaping @Sendable (InjectionPreparationResult) -> Void
    )

    func currentChangeCount() -> Int

    /// Dispatches `.privateState` Cmd+V with userData `0x4C444943`, invoking optional `prePostGuard`
    /// synchronously on `clipboardQueue` immediately before posting Cmd+V, then restores snapshot after
    /// `restoreDelayMs` if `changeCount` still matches `preparation.expectedChangeCount`.
    func dispatchSyntheticPaste(
        preparation: InjectionPreparation,
        restoreDelayMs: Int,
        prePostGuard: (@Sendable () -> Bool)?,
        completion: @escaping @Sendable (Bool) -> Void
    )

    /// Immediately restores snapshot if commit revalidation failed prior to dispatch and changeCount still matches.
    func restoreIfOwned(preparation: InjectionPreparation)

    /// Plain user copy for RecoveryPanel `[复制]` (no transient tag, no auto-restore).
    func copyTextForUser(_ text: String)
}

public extension ClipboardInjecting {
    func dispatchSyntheticPaste(
        preparation: InjectionPreparation,
        restoreDelayMs: Int,
        completion: @escaping @Sendable (Bool) -> Void
    ) {
        dispatchSyntheticPaste(
            preparation: preparation,
            restoreDelayMs: restoreDelayMs,
            prePostGuard: nil,
            completion: completion
        )
    }
}
